import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { createClient } from "@supabase/supabase-js";

function loadEnv(path) {
  const env = {};
  for (const rawLine of readFileSync(path, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^([\w.-]+)\s*=\s*(.*)$/);
    if (!match) continue;
    env[match[1]] = match[2].trim().replace(/^["']|["']$/g, "");
  }
  return env;
}

function password() {
  return `Ts-${randomBytes(18).toString("base64url")}!9a`;
}

function localAdminEmail() {
  return `admin-${Date.now()}@hello.tracksyra.com`;
}

const env = loadEnv(".env");
const supabaseUrl = env.SUPABASE_URL || env.VITE_SUPABASE_URL;
const serviceRoleKey = env.SUPABASE_SERVICE_ROLE_KEY;
if (!supabaseUrl || !serviceRoleKey) {
  console.error(JSON.stringify({ ok: false, error: "Missing Supabase URL or service role key" }));
  process.exit(1);
}

const supabase = createClient(supabaseUrl, serviceRoleKey, {
  auth: { persistSession: false, autoRefreshToken: false },
});

const existingRoles = await supabase.from("user_roles").select("user_id").eq("role", "admin");
if (existingRoles.error) {
  console.error(JSON.stringify({ ok: false, error: existingRoles.error.message }));
  process.exit(1);
}

const existingAdmins = [];
for (const row of existingRoles.data || []) {
  const user = await supabase.auth.admin.getUserById(row.user_id);
  if (user.data?.user?.email) {
    existingAdmins.push({
      id: row.user_id,
      email: user.data.user.email,
      confirmed: Boolean(user.data.user.email_confirmed_at),
      last_sign_in_at: user.data.user.last_sign_in_at || null,
    });
  }
}

if (existingAdmins.length > 0) {
  console.log(JSON.stringify({ ok: true, created: false, admins: existingAdmins }, null, 2));
  process.exit(0);
}

const email = env.ADMIN_EMAIL || localAdminEmail();
const generatedPassword = env.ADMIN_PASSWORD || password();
const created = await supabase.auth.admin.createUser({
  email,
  password: generatedPassword,
  email_confirm: true,
  user_metadata: {
    full_name: "TrackSyra Admin",
    artist_name: "Admin",
  },
  app_metadata: {
    role: "admin",
  },
});

if (created.error) {
  console.error(JSON.stringify({ ok: false, error: created.error.message }));
  process.exit(1);
}

const userId = created.data.user.id;
const role = await supabase.from("user_roles").upsert(
  { user_id: userId, role: "admin" },
  { onConflict: "user_id,role" },
);
if (role.error) {
  console.error(JSON.stringify({ ok: false, error: role.error.message, user_id: userId }));
  process.exit(1);
}

const credentialsPath = ".admin-credentials.local";
if (!env.ADMIN_PASSWORD && !existsSync(credentialsPath)) {
  writeFileSync(
    credentialsPath,
    [
      "# Generated by scripts/ensure-admin-account.mjs",
      "# Store securely and rotate after first login.",
      `ADMIN_EMAIL=${email}`,
      `ADMIN_PASSWORD=${generatedPassword}`,
      "",
    ].join("\n"),
    { mode: 0o600 },
  );
}

console.log(JSON.stringify({
  ok: true,
  created: true,
  admin: {
    id: userId,
    email,
    confirmed: true,
  },
  credentials_location: env.ADMIN_PASSWORD ? "ADMIN_PASSWORD env var" : credentialsPath,
}, null, 2));
